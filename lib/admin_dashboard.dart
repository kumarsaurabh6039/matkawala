          Expanded(
            child: StreamBuilder<QuerySnapshot>(
              stream: FirebaseFirestore.instance.collection('users')
                  .where('role', isEqualTo: 'user')
                  .where('createdBy', isEqualTo: currentAdminId) 
                  .snapshots(),
              builder: (context, snapshot) {
