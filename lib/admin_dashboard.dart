Future<void> generateAndDownloadPdf({
  required BuildContext context,
  required String title,
  required List<List<String>> headers,
  required List<List<String>> rows,
  List<String>? summaryLines,
}) async {
  final pdf = pw.Document();
  pdf.addPage(
    pw.MultiPage(
      pageFormat: PdfPageFormat.a4,
      build: (pw.Context ctx) => [
        pw.Center(child: pw.Text(title, style: pw.TextStyle(fontSize: 18, fontWeight: pw.FontWeight.bold))),
        pw.SizedBox(height: 8),
        pw.Text("Date: ${DateFormat('dd-MM-yyyy').format(DateTime.now())}", style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey600)),
        pw.SizedBox(height: 12),
        pw.Table(
          border: pw.TableBorder.all(color: PdfColors.grey400, width: 0.5),
          children: [
            pw.TableRow(
              decoration: const pw.BoxDecoration(color: PdfColors.blueGrey800),
              children: headers[0].map((h) => pw.Padding(
                padding: const pw.EdgeInsets.all(6),
                child: pw.Text(h, style: pw.TextStyle(color: PdfColors.white, fontWeight: pw.FontWeight.bold, fontSize: 10)),
              )).toList(),
            ),
            ...rows.asMap().entries.map((entry) => pw.TableRow(
              decoration: pw.BoxDecoration(color: entry.key % 2 == 0 ? PdfColors.white : PdfColors.grey100),
              children: entry.value.map((cell) => pw.Padding(
                padding: const pw.EdgeInsets.all(5),
                child: pw.Text(cell, style: const pw.TextStyle(fontSize: 9)),
              )).toList(),
            )),
          ],
        ),
        if (summaryLines != null) ...[
          pw.SizedBox(height: 16),
          pw.Container(
            padding: const pw.EdgeInsets.all(10),
            decoration: const pw.BoxDecoration(color: PdfColors.blueGrey50),
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: summaryLines.map((line) => pw.Text(line, style: const pw.TextStyle(fontSize: 10))).toList(),
            ),
          ),
        ],
        pw.SizedBox(height: 20),
        pw.Center(child: pw.Text("* Generated by MATKAWALA Admin Panel *", style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey))),
      ],
    ),
  );
  await Printing.layoutPdf(
    onLayout: (format) async => pdf.save(),
    name: '${title.replaceAll(' ', '_')}_${DateFormat('dd-MM-yyyy').format(DateTime.now())}.pdf',
  );
}

class AdminDashboard extends StatefulWidget {
  const AdminDashboard({super.key});

  @override
  State<AdminDashboard> createState() => _AdminDashboardState();
}

class _AdminDashboardState extends State<AdminDashboard> {
  int _selectedIndex = 0;

  void _switchTab(int index) {
    setState(() {
      _selectedIndex = index;
    });
  }

  // --- ACCESS DENIED WIDGET ---
  Widget _buildAccessDenied() {
    return Center(
      child: Column(
        mainAxisAlignment: MainAxisAlignment.center,
        children: const [
          Icon(Icons.lock_outline, size: 64, color: Colors.grey),
          SizedBox(height: 16),
          Text(
            "Access Denied\n(तुम्हाला हा विभाग पाहण्याची परवानगी नाही)", 
            textAlign: TextAlign.center, 
            style: TextStyle(color: Colors.grey, fontSize: 16, fontWeight: FontWeight.bold)
          ),
        ],
      )
    );
  }

  @override
  Widget build(BuildContext context) {
    String uid = FirebaseAuth.instance.currentUser?.uid ?? "";

    // Stream for current Admin's Permissions
    return StreamBuilder<DocumentSnapshot>(
      stream: FirebaseFirestore.instance.collection('users').doc(uid).snapshots(),
      builder: (context, snapshot) {
        if (!snapshot.hasData) return const Scaffold(body: Center(child: CircularProgressIndicator(color: kPrimary)));
        
        var adminData = snapshot.data!.data() as Map<String, dynamic>? ?? {};
        Map<String, dynamic> perms = adminData['permissions'] ?? {};

        // Boolean Permissions
        bool pUsers = perms['manage_users'] ?? true;
        bool pPayments = perms['manage_payments'] ?? true;
        bool pGames = perms['edit_games'] ?? true;
        bool pLedger = perms['view_ledger'] ?? true;
        bool pManual = perms['manual_panel'] ?? true;

        final List<Widget> pages = [
          AdminHomePage(onTabSelected: _switchTab, perms: perms), 
          pLedger ? const AdminMarketTab() : _buildAccessDenied(), 
          pGames ? const MarketManagePage() : _buildAccessDenied(), 
          pUsers ? const ManageUsersPage() : _buildAccessDenied(),    
          pLedger ? const AdminSlipPage() : _buildAccessDenied(),         
          pManual ? const ManualPanelPage() : _buildAccessDenied(),    
          const AdminChatTab(), 
        ];

        return Scaffold(
          backgroundColor: kAdminBg,
          appBar: AppBar(
            title: const Text(
              'अॅडमिन पॅनेल (Management Panel)', 
              style: TextStyle(fontWeight: FontWeight.bold, color: kPrimary, fontSize: 18)
            ),
            backgroundColor: Colors.white,
            elevation: 1,
            iconTheme: const IconThemeData(color: kTextMain),
            actions: [
              IconButton(
                onPressed: () => FirebaseAuth.instance.signOut(),
                icon: const Icon(Icons.logout, color: kAccent),
                tooltip: "लॉगआउट करा",
              )
            ],
          ),
          bottomNavigationBar: BottomNavigationBar(
            backgroundColor: Colors.white,
            currentIndex: _selectedIndex,
            onTap: _switchTab,
            selectedItemColor: kPrimary,
            unselectedItemColor: Colors.grey,
            type: BottomNavigationBarType.fixed,
            items: const [
              BottomNavigationBarItem(icon: Icon(Icons.dashboard), label: 'डॅशबोर्ड'),
              BottomNavigationBarItem(icon: Icon(Icons.store), label: 'मार्केट'),
              BottomNavigationBarItem(icon: Icon(Icons.settings_input_component), label: 'गेम्स'),
              BottomNavigationBarItem(icon: Icon(Icons.people), label: 'एजंट'),
