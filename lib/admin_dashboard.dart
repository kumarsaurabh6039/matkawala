  bool _isValidPanna(String panna) {
    if (panna.length != 3) return false;
    int val(String char) {
      int v = int.tryParse(char) ?? 0;
      return v == 0 ? 10 : v; // 0 ki value 10 maano
    }
    int d1 = val(panna[0]);
